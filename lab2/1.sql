/*
Сделать запрос для получения атрибутов из указанных таблиц, применив фильтры по указанным условиям:
Н_ТИПЫ_ВЕДОМОСТЕЙ, Н_ВЕДОМОСТИ.
Вывести атрибуты: Н_ТИПЫ_ВЕДОМОСТЕЙ.НАИМЕНОВАНИЕ, Н_ВЕДОМОСТИ.ДАТА.
Фильтры (AND):
a) Н_ТИПЫ_ВЕДОМОСТЕЙ.ИД = 1.
b) Н_ВЕДОМОСТИ.ЧЛВК_ИД = 117219.
Вид соединения: INNER JOIN.
*/

SELECT ТВ.НАИМЕНОВАНИЕ, В.ДАТА
FROM Н_ТИПЫ_ВЕДОМОСТЕЙ AS ТВ INNER JOIN Н_ВЕДОМОСТИ AS В ON В.ТВ_ИД = ТВ.ИД
WHERE ТВ.ИД = 1 AND В.ЧЛВК_ИД = 117219;